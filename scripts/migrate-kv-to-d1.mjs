#!/usr/bin/env node
/**
 * KV → D1 migration (FABLE5-PLAN Phase 1.3).
 * Reads a kv-snapshot.sh dump of the old `LIBRARY` namespace (sav-content-library)
 * and emits SQL INSERTs. Old structured fields are junk (audit S2), so entries
 * migrate as '0-legacy': full_analysis → legacy_markdown + source meta + tags.
 * The old library is an archive, not a foundation — re-analyze anything worth reusing.
 *
 * Usage:
 *   node scripts/migrate-kv-to-d1.mjs library-snapshot.json > migration-import.sql
 *   🔑 wrangler d1 execute ugc_library --remote --file=migration-import.sql
 */
import { readFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('usage: migrate-kv-to-d1.mjs <snapshot.json>');
  process.exit(1);
}
const snapshot = JSON.parse(readFileSync(file, 'utf8'));

const sq = (v) => (v === null || v === undefined) ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`;
const num = (v) => (typeof v === 'number' && Number.isFinite(v)) ? v : 'NULL';

function detectPlatform(url) {
  if (!url) return null;
  const u = String(url).toLowerCase();
  if (u.includes('tiktok.com')) return 'tiktok';
  if (u.includes('instagram.com') || u.includes('instagr.am')) return 'instagram';
  if (u.includes('youtube.com') || u.includes('youtu.be')) return 'youtube';
  if (u.includes('pinterest.com') || u.includes('pin.it')) return 'pinterest';
  return 'upload';
}

let count = 0, skipped = 0;
const lines = ['-- generated by migrate-kv-to-d1.mjs — 0-legacy import', 'BEGIN TRANSACTION;'];

for (const [key, value] of Object.entries(snapshot)) {
  // skip the index key and anything non-object
  if (key === 'index' || value === null || typeof value !== 'object' || Array.isArray(value)) { skipped++; continue; }
  const e = value;
  // tolerate both libraries' field spellings
  const id = e.id || key.replace(/^entry:/, '');
  const title = e.name || e.title || e.hook_analysis?.slice?.(0, 60) || e.hookText?.slice?.(0, 60) || `Legacy entry ${id.slice(0, 8)}`;
  const archetype = e.category || e.format_type || e.formatType || 'legacy';
  const model = e.model || null;
  const sourceUrl = e.source_url || e.sourceUrl || null;
  const markdown = e.full_analysis || e.fullAnalysis || null;
  const created = e.added || e.savedAt || e.created_at || new Date().toISOString();
  const duration = num(e.video_duration ?? e.duration);
  const clipCount = num(e.clip_count ?? e.clipCount);
  const platform = detectPlatform(sourceUrl);

  if (!markdown && !sourceUrl) { skipped++; continue; }  // nothing recoverable

  const dnaStub = JSON.stringify({
    legacy: true,
    migratedFrom: key,
    note: 'Pre-rebuild KV entry. Structured fields were unreliable (audit S2) and were not migrated. Re-analyze the source video through /analyze for clean DNA.',
    model,
  });

  lines.push(
    `INSERT OR IGNORE INTO formats (id, title, archetype, hook_type, content_rating, duration_sec, clip_count, platform, source_url, thumbnail_url, schema_version, current_version, dna, legacy_markdown, created_at, updated_at)` +
    ` VALUES (${sq(id)}, ${sq(title)}, ${sq(archetype)}, NULL, NULL, ${duration}, ${clipCount}, ${sq(platform)}, ${sq(sourceUrl)}, NULL, '0-legacy', 1, ${sq(dnaStub)}, ${sq(markdown)}, ${sq(created)}, ${sq(created)});`
  );
  for (const tag of new Set(['legacy', model, archetype].filter(Boolean).map((t) => String(t).toLowerCase()))) {
    lines.push(`INSERT OR IGNORE INTO format_tags (format_id, tag) VALUES (${sq(id)}, ${sq(tag)});`);
  }
  count++;
}

lines.push('COMMIT;');
console.log(lines.join('\n'));
console.error(`\n${count} entries migrated, ${skipped} skipped (index key / empty / unrecoverable)`);
